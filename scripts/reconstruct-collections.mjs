#!/usr/bin/env node
// Recover collection-member minutes omitted by Spotify's saved top-50 lists.
// Only monthly totals are written; raw timestamps, account details and IDs stay local.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findFiles, monthOf, cleanTrack } from './lib/history.mjs';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const artistKey = s => String(s).toLowerCase().normalize('NFC').replace(/[^\p{L}\p{N}]+/gu, '');
// Feature credits are spelling variants. Live recordings and remixes are not.
const songKey = s => artistKey(cleanTrack(s).replace(/\((?:feat\.|featuring|with) [^)]*\)/gi, ''));
export function reconstructCollections(groups, covered, streams) {
  const tracks = new Map(groups.flatMap(g => g.releases.map(title =>
    [artistKey(g.artist) + '|' + songKey(title), { title, artist: g.artist }])));
  const seen = new Set(), byMonth = new Map();
  for (const row of streams) {
    if (!row.master_metadata_track_name) continue;
    const track = tracks.get(artistKey(row.master_metadata_album_artist_name) + '|' + songKey(row.master_metadata_track_name));
    if (!track || !Number.isFinite(row.ms_played) || row.ms_played < 0) continue;
    const duplicate = row.ts + '|' + row.spotify_track_uri + '|' + row.ms_played;
    if (seen.has(duplicate)) continue;
    seen.add(duplicate);
    const month = monthOf(row.ts);
    if (!covered.has(month)) continue;
    if (!byMonth.has(month)) byMonth.set(month, new Map());
    const key = track.title + ' — ' + track.artist, entries = byMonth.get(month);
    if (!entries.has(key)) entries.set(key, { ...track, ms: 0 });
    entries.get(key).ms += row.ms_played;
  }
  const months = [...byMonth].sort(([a], [b]) => a.localeCompare(b)).map(([month, entries]) => ({
    month, source: 'spotify',
    albums: [...entries.values()].map(e => [e.title, e.artist, Math.round(e.ms / 60000)])
      .filter(row => row[2] > 0).sort((a, b) => b[2] - a[2] || a[0].localeCompare(b[0]))
  })).filter(m => m.albums.length);
  return {
    _comment: 'Generated by scripts/reconstruct-collections.mjs. Recorded Spotify playback, rounded per single per month. Replace matching source/release totals; never add on top. Does not estimate missing Apple or Deezer listening.',
    collections: groups.map(g => ({ title: g.title, artist: g.artist, source: 'spotify', method: 'recorded-playback' })),
    months
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sourceDir = resolve(ROOT, process.argv[2] || 'spotify data');
  const groups = JSON.parse(readFileSync(join(ROOT, 'data/releases.json'), 'utf8')).groups.filter(g => g.kind === 'Singles collection');
  const covered = new Set(readdirSync(join(ROOT, 'data/spotify')).filter(f => /^\d{4}-\d{2}\.json$/.test(f)).map(f => f.slice(0, 7)));
  const files = findFiles(sourceDir, /^Streaming_History_Audio_.*\.json$/);
  if (!files.length) throw new Error('No Spotify extended-history files found. Existing reconstruction left untouched.');
  function* streams() { for (const file of files) yield* JSON.parse(readFileSync(file, 'utf8')); }
  const out = reconstructCollections(groups, covered, streams());
  writeFileSync(join(ROOT, 'data/collection-listening.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(`Reconstructed ${groups.length} collection(s) across ${out.months.length} covered Spotify months from recorded playback time.`);
}
