#!/usr/bin/env node
// Works out which album each charted song comes from, straight from a Spotify export
// (every stream names its album), and writes <folder>/tracks.json for the site.
//
//   node scripts/link-spotify-tracks.mjs p2 profiles/l
//
// A song is listed under the album it was streamed from most, if that album charted too.
// Entries already in tracks.json are kept, so hand fixes survive a re-run.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findFiles, cleanTrack, cleanAlbum } from './lib/history.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const [src, dir] = process.argv.slice(2);
if (!src || !dir) { console.error('usage: link-spotify-tracks.mjs <export folder> <data folder>'); process.exit(1); }
const norm = s => String(s).toLowerCase().normalize('NFC').replace(/\([^)]*\)|\[[^\]]*\]/g, '').replace(/[^\p{L}\p{N}]+/gu, '');

// charted songs and albums (any rank in the saved lists counts as "charted" for linking)
const songs = new Map(), albums = new Map();
for (const sub of ['spotify', 'charts', 'deezer']) {
  const d = join(ROOT, dir, sub); if (!existsSync(d)) continue;
  for (const f of readdirSync(d).filter(f => /^\d{4}-\d{2}\.json$/.test(f))) {
    const m = JSON.parse(readFileSync(join(d, f), 'utf8'));
    m.songs.forEach(([t, a]) => songs.set(norm(t) + '|' + norm(a), [t, a]));
    m.albums.forEach(([t, a]) => { const l = albums.get(norm(t)) || []; if (!l.some(x => x[1] === a)) l.push([t, a]); albums.set(norm(t), l); });
  }
}
// minutes per (song, album) from the raw streams
const by = new Map();
for (const f of findFiles(join(ROOT, src), /^Streaming_History_Audio_.*\.json$/)) {
  for (const r of JSON.parse(readFileSync(f, 'utf8'))) {
    if (!r.master_metadata_track_name || !r.master_metadata_album_album_name) continue;
    const sk = norm(cleanTrack(r.master_metadata_track_name)) + '|' + norm(r.master_metadata_album_artist_name);
    if (!songs.has(sk)) continue;
    const ak = norm(cleanAlbum(r.master_metadata_album_album_name));
    const m = by.get(sk) || new Map(); m.set(ak, (m.get(ak) || 0) + r.ms_played); by.set(sk, m);
  }
}
const path = join(ROOT, dir, 'tracks.json');
const tracks = existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : {};
tracks._comment = tracks._comment || 'Charted songs grouped under the charted album they come from. "Album — Album artist": ["Song", or "Song — Song artist" when the credit differs]. Generated by scripts/link-spotify-tracks.mjs; edit freely.';
const placed = new Set(Object.entries(tracks).filter(([k]) => k !== '_comment').flatMap(([k, v]) => {
  const aa = k.slice(k.lastIndexOf(' — ') + 3);
  return v.map(s => { const j = s.lastIndexOf(' — '); return j < 0 ? norm(s) + '|' + norm(aa) : norm(s.slice(0, j)) + '|' + norm(s.slice(j + 3)); });
}));
let linked = 0;
for (const [sk, [t, a]] of songs) {
  if (placed.has(sk) || !by.has(sk)) continue;
  const [ak] = [...by.get(sk)].sort((x, y) => y[1] - x[1])[0];
  const list = albums.get(ak); if (!list) continue;
  const album = list.find(x => norm(x[1]) === norm(a)) || list[0];
  const key = album[0] + ' — ' + album[1];
  (tracks[key] = tracks[key] || []).push(a === album[1] ? t : t + ' — ' + a);
  linked++;
}
const keys = Object.keys(tracks).filter(k => k !== '_comment').sort();
writeFileSync(path, '{\n  "_comment": ' + JSON.stringify(tracks._comment) + (keys.length ? ',\n' : '\n') +
  keys.map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(tracks[k])).join(',\n') + '\n}\n');
console.log(`${dir}/tracks.json: linked ${linked} of ${songs.size} songs to ${keys.length} albums`);
